export { ISO_639_1 };

export const languageCodeSchema = z.enum(ISO_639_1, {
	errorMap: (issue) => {
		if (issue.code === 'invalid_enum_value') {
			return {
				message:
					'is not a valid language code (use ISO 639-1 codes https://en.wikipedia.org/wiki/List_of_ISO_639_language_codes)'
			};
		}
		return { message: issue.message ?? 'invalid' };
	}
});

type TranslationPrimitiveValue_Input = string | number | boolean;
type TranslationValue_Input =
	| TranslationPrimitiveValue_Input
	| { [key: string]: TranslationValue_Input };

type TranslationValue = string | { [key: string]: TranslationValue };
const translationValueSchema: z.ZodType<TranslationValue, z.ZodTypeDef, TranslationValue_Input> =
	z.lazy(() =>
		z.union([
			z.union([z.string(), z.number(), z.boolean()]).transform((val) => val.toString()),
			z.record(z.string(), translationValueSchema)
		])
	);

export const translationMapSchema = z.record(z.string(), translationValueSchema);
export const translationsYamlSchema = z.record(languageCodeSchema, translationMapSchema);

export type TranslationMap = z.infer<typeof translationMapSchema>;
// Map of language codes to their translation maps: { en: { greeting: "Hello" }, es: { greeting: "Hola" } }
export type TranslationsMap = Record<string, TranslationMap>;
